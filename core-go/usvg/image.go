// ImageHrefResolver resolves `xlink:href` in `image` elements. Replace it to forbid local files or to
// fetch urls (usvg makes no network requests). A nil func resolves nothing.
type ImageHrefResolver struct {
	// ResolveData handles a data url: mime is `type/subtype` (lower case) and data the decoded payload.
	ResolveData func(mime string, data []byte, opt *Options) (ImageKind, bool)
	// ResolveString handles any other href.
	ResolveString func(href string, opt *Options) (ImageKind, bool)
}

// DefaultImageHrefResolver is ImageHrefResolver::default().
func DefaultImageHrefResolver() ImageHrefResolver {
	return ImageHrefResolver{ResolveData: DefaultDataResolver(), ResolveString: DefaultStringResolver()}
}

// DefaultDataResolver is ImageHrefResolver::default_data_resolver: JPEG, PNG, GIF, WebP and SVG(Z) by
// mime type, with `text/plain` sniffed by magic bytes (anything else is tried as SVG). Raster data is
// not decoded; that is up to the renderer.
func DefaultDataResolver() func(mime string, data []byte, opt *Options) (ImageKind, bool) {
	return func(mime string, data []byte, opt *Options) (ImageKind, bool) {
		switch mime {
		case "image/jpg", "image/jpeg":
			return ImageKindJPEG(data), true
		case "image/png":
			return ImageKindPNG(data), true
		case "image/gif":
			return ImageKindGIF(data), true
		case "image/webp":
			return ImageKindWEBP(data), true
		case "image/svg+xml":
			return loadSubSVG(data, opt)
		case "text/plain":
			f, ok := getImageDataFormat(data)
			switch {
			case !ok:
			case f == imageFormatJPEG:
				return ImageKindJPEG(data), true
			case f == imageFormatPNG:
				return ImageKindPNG(data), true
			case f == imageFormatGIF:
				return ImageKindGIF(data), true
			case f == imageFormatWEBP:
				return ImageKindWEBP(data), true
			}
			return loadSubSVG(data, opt)
		}
		return nil, false
	}
}

// DefaultStringResolver is ImageHrefResolver::default_string_resolver: href is a file path, absolute or
// relative to Options.ResourcesDir (the working directory without one); urls and the rest are ignored.
func DefaultStringResolver() func(href string, opt *Options) (ImageKind, bool) {
	return func(href string, opt *Options) (ImageKind, bool) {
		path := opt.GetAbsPath(href)
		if _, err := os.Stat(path); err != nil {
			return nil, false // not a path to an image
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, false
		}
		f, ok := getImageFileFormat(path, data)
		if !ok {
			return nil, false // not a PNG, JPEG, GIF, WebP or SVG(Z) image
		}
		switch f {
		case imageFormatJPEG:
			return ImageKindJPEG(data), true
		case imageFormatPNG:
			return ImageKindPNG(data), true
		case imageFormatGIF:
			return ImageKindGIF(data), true
		case imageFormatWEBP:
			return ImageKindWEBP(data), true
		}
		return loadSubSVG(data, opt)
	}
}

type imageFormat uint8

const (
	imageFormatPNG imageFormat = iota
	imageFormatJPEG
	imageFormatGIF
	imageFormatWEBP
	imageFormatSVG
)

// convertImage is image::convert.
func convertImage(node svgNode, state *converterState, cache *converterCache, parent *Group) {
	href, ok := svgTryAttr(node, aidHref, svgParseStr)
	if !ok {
		return // the image lacks `xlink:href`
	}
	kind, ok := getHrefData(href, state)
	if !ok {
		return
	}

	vis, _ := svgFindAttr(node, aidVisibility, svgNode.attrVisibility)
	visible := vis == visibilityVisible

	renderingMode, ok := svgFindAttr(node, aidImageRendering, svgNode.attrImageRendering)
	if !ok {
		renderingMode = state.opt.ImageRendering
	}

	// Nodes generated by markers must not have an ID, or there would be duplicates.
	id := ""
	if len(state.parentMarkers) == 0 {
		id = node.ElementID()
	}

	actualSize, ok := kind.actualSize()
	if !ok {
		return
	}

	x := node.convertUserLength(aidX, state, stLengthZero())
	y := node.convertUserLength(aidY, state, stLengthZero())
	width := node.convertUserLength(aidWidth, state, stNewLengthNumber(float64(actualSize.Width())))
	height := node.convertUserLength(aidHeight, state, stNewLengthNumber(float64(actualSize.Height())))

	_, hasW := node.attrLength(aidWidth)
	_, hasH := node.attrLength(aidHeight)
	switch {
	case hasW && !hasH:
		// Only the width is set: scale the height to match.
		height = float32(actualSize.Height() * float32(width/actualSize.Width()))
	case !hasW && hasH:
		// Only the height is set: scale the width to match.
		width = float32(actualSize.Width() * float32(height/actualSize.Height()))
	}

	aspect, ok := node.attrAspectRatio(aidPreserveAspectRatio)
	if !ok {
		aspect = stDefaultAspectRatio()
	}

	rect, ok := skia.NonZeroRectFromXYWH(x, y, width, height)
	if !ok {
		return // the image has an invalid size
	}

	convertImageInner(kind, id, visible, renderingMode, aspect, actualSize, rect, cache, parent)
}

// convertImageInner is image::convert_inner: the image in a group carrying its view box transform,
// inside a clipping group when the aspect ratio slices.
func convertImageInner(kind ImageKind, id string, visible bool, renderingMode ImageRendering,
	aspect stAspectRatio, actualSize skia.Size, rect skia.NonZeroRect, cache *converterCache,
	parent *Group) bool {
	alignedSize := fitViewBox(actualSize, rect, aspect)
	alignedX, alignedY := alignedPos(aspect.Align, rect.X(), rect.Y(),
		rect.Width()-alignedSize.Width(), rect.Height()-alignedSize.Height())
	viewBox := alignedSize.ToNonZeroRect(alignedX, alignedY)

	imageTS := skia.TransformFromRow(viewBox.Width()/actualSize.Width(), 0, 0,
		viewBox.Height()/actualSize.Height(), viewBox.X(), viewBox.Y())

	absTransform := parent.absTransform.PreConcat(imageTS)
	absBoundingBox, ok := viewBox.Transform(parent.absTransform)
	if !ok {
		return false
	}

	g := newEmptyGroup()
	g.id = id
	g.children = append(g.children, &Image{
		visible:        visible,
		size:           actualSize,
		renderingMode:  renderingMode,
		kind:           kind,
		absTransform:   absTransform,
		absBoundingBox: absBoundingBox,
	})
	g.transform = imageTS
	g.absTransform = absTransform
	g.calculateBoundingBoxes()

	if aspect.Slice {
		// A sliced image acts like a rectangular clip, which the view box transform must not affect:
		// <g clip-path="url(#clipPath1)"><g transform="matrix(1 0 0 1 10 20)"><image/></g></g>
		path, ok := newSimplePath(skia.PathFromRect(rect.ToRect()))
		if !ok {
			panic("usvg: image clip path") // Rust unwraps
		}
		fill := DefaultFill()
		path.fill = &fill

		clip := newEmptyClipPath(cache.genClipPathID())
		clip.root.children = append(clip.root.children, path)

		g2 := newEmptyGroup()
		g.id, g2.id = g2.id, g.id
		g2.absTransform = parent.absTransform
		g2.clipPath = clip
		g2.children = append(g2.children, &g)
		g2.calculateBoundingBoxes()

		parent.children = append(parent.children, &g2)
	} else {
		parent.children = append(parent.children, &g)
	}
	return true
}

// getHrefData is get_href_data: a data url goes to ResolveData (an undecodable one resolves nothing),
// anything else to ResolveString.
func getHrefData(href string, state *converterState) (ImageKind, bool) {
	resolver := state.opt.ImageHrefResolver
	if url, ok := imageProcessDataURL(href); ok {
		data, ok := url.decodeToVec()
		if !ok {
			return nil, false
		}
		if resolver.ResolveData == nil {
			return nil, false
		}
		return resolver.ResolveData(url.mimeType+"/"+url.mimeSubtype, data, state.opt)
	}
	if resolver.ResolveString == nil {
		return nil, false
	}
	return resolver.ResolveString(href, state.opt)
}

// getImageFileFormat is get_image_file_format: an `svg` or `svgz` extension (any case), else the
// magic bytes of a PNG, GIF, JPEG or WebP.
func getImageFileFormat(path string, data []byte) (imageFormat, bool) {
	// Path::extension: the file name's part after the last dot, none for a name starting with its only
	// dot (or a missing file name). A file name exists only when the path is not empty.
	name := filepath.Base(path)
	dot := strings.LastIndexByte(name, '.')
	if path == "" || name == "." || name == ".." || dot <= 0 {
		return 0, false
	}
	ext := strings.ToLower(name[dot+1:])
	if ext == "svg" || ext == "svgz" {
		return imageFormatSVG, true
	}
	return getImageDataFormat(data)
}

// getImageDataFormat is get_image_data_format: the magic bytes of a PNG, GIF, JPEG or WebP.
func getImageDataFormat(data []byte) (imageFormat, bool) {
	t, err := imgszGetImageType(data)
	if err != nil {
		return 0, false
	}
	switch t {
	case imgszTypeGif:
		return imageFormatGIF, true
	case imgszTypeJpeg:
		return imageFormatJPEG, true
	case imgszTypePng:
		return imageFormatPNG, true
	case imgszTypeWebp:
		return imageFormatWEBP, true
	}
	return 0, false
}

// loadSubSVG is load_sub_svg: the data as a nested SVG, or nothing when it does not parse.
func loadSubSVG(data []byte, opt *Options) (ImageKind, bool) {
	tree, err := FromDataNested(data, opt)
	if err != nil {
		return nil, false
	}
	return ImageKindSVG{Tree: tree}, true
}

// fitViewBox fits size into rect as aspect says.
func fitViewBox(size skia.Size, rect skia.NonZeroRect, aspect stAspectRatio) skia.Size {
	s := rect.Size()
	if aspect.Align == stAlignNone {
		return s
	} else if aspect.Slice {
		return size.ExpandTo(s)
	}
	return size.ScaleTo(s)
}

// imageDataURL is data_url::DataUrl: a processed `data:` url.
type imageDataURL struct {
	mimeType, mimeSubtype string
	base64                bool
	encodedBodyPlusFrag   string
}

// imageIsC0OrSpace is `ch <= ' '`, data-url's "C0 control or space".
func imageIsC0OrSpace(c byte) bool { return c <= ' ' }

// imageIsTabOrNewline matches the bytes the URL parser removes.
func imageIsTabOrNewline(c byte) bool { return c == '\t' || c == '\n' || c == '\r' }

// imageProcessDataURL is DataUrl::process; ok is false when input is not a data url or has no comma
// before its fragment.
func imageProcessDataURL(input string) (imageDataURL, bool) {
	// pretend_parse_data_url
	i := 0
	for i < len(input) && imageIsC0OrSpace(input[i]) {
		i++
	}
	const scheme = "data:"
	for k := 0; k < len(scheme); {
		if i >= len(input) {
			return imageDataURL{}, false
		}
		c := input[i]
		i++
		if imageIsTabOrNewline(c) {
			continue
		}
		if k < 4 && c >= 'A' && c <= 'Z' {
			c += 'a' - 'A'
		}
		if c != scheme[k] {
			return imageDataURL{}, false
		}
		k++
	}
	afterColon := input[i:]
	end := len(afterColon)
	for end > 0 && imageIsC0OrSpace(afterColon[end-1]) {
		end--
	}
	afterColon = afterColon[:end]

	// find_comma_before_fragment
	comma := -1
	for j := 0; j < len(afterColon); j++ {
		if afterColon[j] == ',' {
			comma = j
			break
		}
		if afterColon[j] == '#' {
			return imageDataURL{}, false
		}
	}
	if comma < 0 {
		return imageDataURL{}, false
	}

	typ, sub, b64 := imageParseDataURLHeader(afterColon[:comma])
	return imageDataURL{mimeType: typ, mimeSubtype: sub, base64: b64, encodedBodyPlusFrag: afterColon[comma+1:]}, true
}

// imageParseDataURLHeader is parse_header: the mime type and subtype, and whether the body is base64.
func imageParseDataURLHeader(fromColonToComma string) (string, string, bool) {
	isWS := func(c byte) bool { return c == ' ' || c == '\t' || c == '\n' || c == '\r' }
	trimmed := fromColonToComma
	for len(trimmed) > 0 && isWS(trimmed[0]) {
		trimmed = trimmed[1:]
	}
	for len(trimmed) > 0 && isWS(trimmed[len(trimmed)-1]) {
		trimmed = trimmed[:len(trimmed)-1]
	}

	mimeType, b64 := imageRemoveBase64Suffix(trimmed)
	if !b64 {
		mimeType = trimmed
	}

	var sb strings.Builder
	if strings.HasPrefix(mimeType, ";") {
		sb.WriteString("text/plain")
	}
	const hex = "0123456789ABCDEF"
	percentEncode := func(c byte) { sb.WriteByte('%'); sb.WriteByte(hex[c>>4]); sb.WriteByte(hex[c&15]) }
	inQuery := false
	for i := 0; i < len(mimeType); i++ {
		c := mimeType[i]
		switch {
		case imageIsTabOrNewline(c):
			continue
		case c <= 0x1f || c >= 0x7f:
			percentEncode(c)
		case inQuery && (c == ' ' || c == '"' || c == '<' || c == '>'):
			percentEncode(c)
		case c == '?':
			inQuery = true
			sb.WriteByte('?')
		default:
			sb.WriteByte(c)
		}
	}

	typ, sub, ok := imageParseMime(sb.String())
	if !ok {
		return "text", "plain", b64
	}
	return typ, sub, b64
}

// imageRemoveBase64Suffix is remove_base64_suffix: s without a trailing `;base64` (any case, spaces
// allowed before it, tabs and newlines ignored); ok is false when there is none.
func imageRemoveBase64Suffix(s string) (string, bool) {
	j := len(s)
	prev := func() (byte, bool) {
		for j > 0 {
			j--
			if !imageIsTabOrNewline(s[j]) {
				return s[j], true
			}
		}
		return 0, false
	}
	lower := func(c byte) byte {
		if c >= 'A' && c <= 'Z' {
			return c + 'a' - 'A'
		}
		return c
	}
	for k, want := range []byte("46esab") {
		c, ok := prev()
		if k >= 2 {
			c = lower(c)
		}
		if !ok || c != want {
			return "", false
		}
	}
	c, ok := prev()
	for ok && c == ' ' {
		c, ok = prev()
	}
	if !ok || c != ';' {
		return "", false
	}
	return s[:j], true
}

// imageIsHTTPToken is data-url's IS_HTTP_TOKEN.
func imageIsHTTPToken(c byte) bool {
	switch {
	case c >= '0' && c <= '9', c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z':
		return true
	}
	return strings.IndexByte("!#$%&'*+-.^_`|~", c) >= 0
}

// imageParseMime is data_url::mime::Mime's FromStr, keeping only the lower-cased type and subtype.
func imageParseMime(s string) (string, string, bool) {
	isWS := func(c byte) bool { return c == ' ' || c == '\t' || c == '\n' || c == '\r' }
	for len(s) > 0 && isWS(s[0]) {
		s = s[1:]
	}
	for len(s) > 0 && isWS(s[len(s)-1]) {
		s = s[:len(s)-1]
	}
	onlyTokens := func(t string) bool {
		for i := 0; i < len(t); i++ {
			if !imageIsHTTPToken(t[i]) {
				return false
			}
		}
		return true
	}
	slash := strings.IndexByte(s, '/')
	typ := s
	if slash >= 0 {
		typ = s[:slash]
	}
	if !onlyTokens(typ) || typ == "" || slash < 0 {
		return "", "", false
	}
	sub := s[slash+1:]
	if semi := strings.IndexByte(sub, ';'); semi >= 0 {
		sub = sub[:semi]
	}
	for len(sub) > 0 && isWS(sub[len(sub)-1]) {
		sub = sub[:len(sub)-1]
	}
	if !onlyTokens(sub) || sub == "" {
		return "", "", false
	}
	return strings.ToLower(typ), strings.ToLower(sub), true
}

// decodeToVec is DataUrl::decode_to_vec: the percent-decoded body up to the fragment, then forgiving
// base64 when the header said so; ok is false for invalid base64.
func (u imageDataURL) decodeToVec() ([]byte, bool) {
	body := imagePercentDecodeBody(u.encodedBodyPlusFrag)
	if !u.base64 {
		return body, true
	}
	return imageForgivingBase64(body)
}

func imageFromHex(c byte) (byte, bool) {
	switch {
	case c >= '0' && c <= '9':
		return c - '0', true
	case c >= 'a' && c <= 'f':
		return c - 'a' + 10, true
	case c >= 'A' && c <= 'F':
		return c - 'A' + 10, true
	}
	return 0, false
}

// imagePercentDecodeBody is decode_without_base64: `%XX` decoded, tabs and newlines dropped, stopping
// at `#`.
func imagePercentDecodeBody(s string) []byte {
	out := make([]byte, 0, len(s))
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '#':
			return out
		case imageIsTabOrNewline(c):
		case c == '%' && i+2 < len(s):
			h, ok1 := imageFromHex(s[i+1])
			l, ok2 := imageFromHex(s[i+2])
			if ok1 && ok2 {
				out = append(out, h*16+l)
				i += 2
			} else {
				out = append(out, c)
			}
		default:
			out = append(out, c)
		}
	}
	return out
}

// imageForgivingBase64 is data-url's forgiving_base64::Decoder: ASCII whitespace skipped, `=` only as
// trailing padding (which may be omitted), leftover bits ignored.
func imageForgivingBase64(in []byte) ([]byte, bool) {
	out := make([]byte, 0, len(in)*3/4)
	var bitBuffer uint32
	bitLength, padding := 0, 0
	for _, c := range in {
		var v byte
		switch {
		case c >= 'A' && c <= 'Z':
			v = c - 'A'
		case c >= 'a' && c <= 'z':
			v = c - 'a' + 26
		case c >= '0' && c <= '9':
			v = c - '0' + 52
		case c == '+':
			v = 62
		case c == '/':
			v = 63
		case c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f':
			continue
		case c == '=':
			padding++
			continue
		default:
			return nil, false
		}
		if padding > 0 {
			return nil, false
		}
		bitBuffer = bitBuffer<<6 | uint32(v)
		if bitLength < 18 {
			bitLength += 6
		} else {
			out = append(out, byte(bitBuffer>>16), byte(bitBuffer>>8), byte(bitBuffer))
			bitLength = 0
		}
	}
	switch {
	case bitLength == 0 && padding == 0:
	case bitLength == 12 && (padding == 0 || padding == 2):
		out = append(out, byte(bitBuffer>>4))
	case bitLength == 18 && (padding == 0 || padding == 1):
		out = append(out, byte(bitBuffer>>10), byte(bitBuffer>>2))
	default:
		return nil, false
	}
	return out, true
}
