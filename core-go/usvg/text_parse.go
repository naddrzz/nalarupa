// charPosition is CharacterPosition: absolute x/y and relative dx/dy of a code point; nil is None.
type charPosition struct {
	x, y, dx, dy *float32
}

// convertText is text::convert: it lays the text out and flattens it, and appends nothing when that
// fails (no fonts, no glyphs, an empty bounding box).
func convertText(textNode svgNode, state *converterState, cache *converterCache, parent *Group) {
	posList := resolvePositionsList(textNode, state)
	rotateList := resolveRotateList(textNode)
	writingMode := convertWritingMode(textNode)

	chunks := collectTextChunks(textNode, posList, state, cache)

	renderingMode := state.opt.TextRendering
	if v, ok := svgFindAttr(textNode, aidTextRendering, svgNode.attrTextRendering); ok {
		renderingMode = v
	}

	// Nodes generated by markers must not have an ID, or there would be duplicates.
	id := ""
	if len(state.parentMarkers) == 0 {
		id = textNode.ElementID()
	}

	dummy, _ := skia.RectFromXYWH(0, 0, 0, 0)
	t := &Text{
		id:                   id,
		renderingMode:        renderingMode,
		dx:                   make([]float32, len(posList)),
		dy:                   make([]float32, len(posList)),
		rotate:               rotateList,
		writingMode:          writingMode,
		chunks:               chunks,
		absTransform:         parent.absTransform,
		boundingBox:          dummy,
		absBoundingBox:       dummy,
		strokeBoundingBox:    dummy,
		absStrokeBoundingBox: dummy,
		flattened:            &Group{},
	}
	*t.flattened = newEmptyGroup()
	for i, p := range posList {
		if p.dx != nil {
			t.dx[i] = *p.dx
		}
		if p.dy != nil {
			t.dy[i] = *p.dy
		}
	}

	if !textConvert(t, state.opt, cache) {
		return
	}
	parent.children = append(parent.children, t)
}

// textIterState is IterState.
type textIterState struct {
	charsCount      int
	chunkBytesCount int
	// texts holds each chunk's text while it grows (chunks[i].text is set at the end).
	texts      []*strings.Builder
	splitChunk bool
	textFlow   *TextPath
	chunks     []TextChunk
}

func collectTextChunks(textNode svgNode, posList []charPosition, state *converterState, cache *converterCache) []TextChunk {
	it := &textIterState{}
	collectTextChunksImpl(textNode, posList, state, cache, it)
	for i := range it.chunks {
		it.chunks[i].text = it.texts[i].String()
	}
	return it.chunks
}

func collectTextChunksImpl(parent svgNode, posList []charPosition, state *converterState, cache *converterCache, it *textIterState) {
	for child := range parent.Children() {
		if child.IsElement() {
			if child.hasTagName(eidTextPath) {
				if !parent.hasTagName(eidText) {
					// `textPath` can be set only as a direct `text` element child.
					it.charsCount += countChars(child)
					continue
				}
				flow, ok := resolveTextFlow(child, state)
				if !ok {
					// Skip an invalid text path and its children, still counting their characters,
					// since posList includes them.
					it.charsCount += countChars(child)
					continue
				}
				it.textFlow = flow
				it.splitChunk = true
			}

			collectTextChunksImpl(child, posList, state, cache, it)
			it.textFlow = nil

			// The next char after `textPath` should be split too.
			if child.hasTagName(eidTextPath) {
				it.splitChunk = true
			}
			continue
		}

		if !parent.isVisibleElement(state.opt) {
			it.charsCount += utf8.RuneCountInString(child.Text())
			continue
		}

		anchor, _ := svgFindAttr(parent, aidTextAnchor, svgNode.attrTextAnchor)

		fontSize, ok := newNonZeroPositiveF32(resolveFontSize(parent, state))
		if !ok {
			// Skip this span.
			it.charsCount += utf8.RuneCountInString(child.Text())
			continue
		}

		font := convertFont(parent, state)

		rawPaintOrder, _ := svgFindAttr(parent, aidPaintOrder, svgNode.attrPaintOrder)
		paintOrder := svgPaintOrderToUsvg(rawPaintOrder)

		dominantBaseline, _ := svgFindAttr(parent, aidDominantBaseline, svgNode.attrDominantBaseline)
		// `no-change` means "use parent".
		if dominantBaseline == DominantBaselineNoChange {
			pe, ok := parent.ParentElement()
			if !ok {
				panic("usvg: text span without a parent element") // Rust unwraps
			}
			dominantBaseline, _ = svgFindAttr(pe, aidDominantBaseline, svgNode.attrDominantBaseline)
		}

		applyKerning := true
		if parent.resolveLength(aidKerning, state, -1) == 0 {
			applyKerning = false
		} else if v, ok := svgFindAttr(parent, aidFontKerning, svgNode.attrStr); ok && v == "none" {
			applyKerning = false
		}

		opticalSizing := FontOpticalSizingAuto
		if v, ok := svgFindAttr(parent, aidFontOpticalSizing, svgNode.attrStr); ok && v == "none" {
			opticalSizing = FontOpticalSizingNone
		}

		textLength, hasTextLength := parent.tryConvertLength(aidTextLength, unitsUserSpaceOnUse, state)
		// Negative values are ignored.
		if hasTextLength && textLength < 0 {
			hasTextLength = false
		}

		vis, _ := svgFindAttr(parent, aidVisibility, svgNode.attrVisibility)

		span := TextSpan{paintOrder: paintOrder, font: font, fontSize: fontSize}
		span.fill = resolveFill(parent, true, state, cache)
		span.stroke = resolveStroke(parent, true, state, cache)
		variant, ok := svgFindAttr(parent, aidFontVariant, svgNode.attrStr)
		span.smallCaps = ok && variant == "small-caps"
		span.applyKerning = applyKerning
		span.fontOpticalSizing = opticalSizing
		span.decoration = resolveDecoration(parent, state, cache)
		span.visible = vis == visibilityVisible
		span.dominantBaseline = dominantBaseline
		span.alignmentBaseline, _ = svgFindAttr(parent, aidAlignmentBaseline, svgNode.attrAlignmentBaseline)
		span.baselineShift = convertBaselineShift(parent, state)
		span.letterSpacing = parent.resolveLength(aidLetterSpacing, state, 0)
		span.wordSpacing = parent.resolveLength(aidWordSpacing, state, 0)
		span.textLength, span.hasTextLength = textLength, hasTextLength
		span.lengthAdjust, _ = svgFindAttr(parent, aidLengthAdjust, svgNode.attrLengthAdjust)

		isNewSpan := true
		for _, c := range child.Text() {
			charLen := utf8.RuneLen(c)
			if charLen < 0 {
				charLen = 3 // U+FFFD for invalid UTF-8, which Go strings may hold and Rust's cannot
			}
			pos := posList[it.charsCount]

			// A new chunk starts at the first span, at a character with an absolute x or y, and at the
			// first character in and after a `textPath`.
			isNewChunk := pos.x != nil || pos.y != nil || it.splitChunk || len(it.chunks) == 0
			it.splitChunk = false

			if isNewChunk {
				it.chunkBytesCount = 0
				span2 := span
				span2.start, span2.end = 0, charLen
				ch := TextChunk{anchor: anchor, spans: []TextSpan{span2}, textFlow: it.textFlow}
				it.texts = append(it.texts, &strings.Builder{})
				it.texts[len(it.texts)-1].WriteRune(c)
				if pos.x != nil {
					ch.x, ch.hasX = *pos.x, true
				}
				if pos.y != nil {
					ch.y, ch.hasY = *pos.y, true
				}
				it.chunks = append(it.chunks, ch)
			} else if isNewSpan {
				// Add this span to the last text chunk.
				span2 := span
				span2.start, span2.end = it.chunkBytesCount, it.chunkBytesCount+charLen
				last := &it.chunks[len(it.chunks)-1]
				it.texts[len(it.texts)-1].WriteRune(c)
				last.spans = append(last.spans, span2)
			} else {
				// Extend the last span.
				last := &it.chunks[len(it.chunks)-1]
				it.texts[len(it.texts)-1].WriteRune(c)
				last.spans[len(last.spans)-1].end += charLen
			}

			isNewSpan = false
			it.charsCount++
			it.chunkBytesCount += charLen
		}
	}
}

// resolveTextFlow is resolve_text_flow: the text path of a `textPath`, or false when it links nowhere
// usable.
func resolveTextFlow(node svgNode, state *converterState) (*TextPath, bool) {
	linked, ok := node.attrNode(aidHref)
	if !ok {
		return nil, false
	}
	path, ok := convertShape(linked, state)
	if !ok {
		return nil, false
	}
	// The reference path's transform needs to be applied.
	if ts := linked.resolveTransform(aidTransform, state); !ts.IsIdentity() {
		if path = path.Transform(ts); path == nil {
			return nil, false
		}
	}

	startOffset, ok := node.attrLength(aidStartOffset)
	if !ok {
		startOffset = stLength{}
	}
	var offset float32
	if startOffset.Unit == stLengthUnitPercent {
		// A percentage is a distance along the entire path.
		offset = float32(float64(pathLength(path) * (startOffset.Number / 100)))
	} else {
		offset = node.resolveLength(aidStartOffset, state, 0)
	}

	id, ok := newNonEmptyString(linked.ElementID())
	if !ok {
		return nil, false
	}
	return &TextPath{id: id, startOffset: offset, path: path}, true
}

// convertFont is convert_font.
func convertFont(node svgNode, state *converterState) Font {
	style, _ := svgFindAttr(node, aidFontStyle, svgNode.attrFontStyle)
	stretch := convFontStretch(node)
	weight := resolveFontWeight(node)
	variations := parseFontVariationSettings(node)

	// Standard font properties map to variation axes unless set explicitly, so variable fonts follow
	// font-weight and font-stretch.
	has := func(t string) bool {
		for _, v := range variations {
			if string(v.Tag[:]) == t {
				return true
			}
		}
		return false
	}
	hasWght, hasWdth, hasItal, hasSlnt := has("wght"), has("wdth"), has("ital"), has("slnt")
	if !hasWght && weight != 400 {
		variations = append(variations, FontVariation{Tag: [4]byte{'w', 'g', 'h', 't'}, Value: float32(weight)})
	}
	if !hasWdth {
		wdth := [...]float32{50, 62.5, 75, 87.5, 100, 112.5, 125, 150, 200}[stretch]
		if wdth != 100 {
			variations = append(variations, FontVariation{Tag: [4]byte{'w', 'd', 't', 'h'}, Value: wdth})
		}
	}
	if !hasItal && style == FontStyleItalic {
		variations = append(variations, FontVariation{Tag: [4]byte{'i', 't', 'a', 'l'}, Value: 1})
	}
	if !hasSlnt && style == FontStyleOblique {
		variations = append(variations, FontVariation{Tag: [4]byte{'s', 'l', 'n', 't'}, Value: -12})
	}

	fontFamilies := ""
	if n, ok := findAncestorWith(node, aidFontFamily); ok {
		fontFamilies, _ = n.attrStr(aidFontFamily)
	}
	var families []FontFamily
	if parsed, err := stParseFontFamilies(fontFamilies); err == nil {
		for _, f := range parsed {
			families = append(families, fontFamilyFromSt(f))
		}
	}
	if len(families) == 0 {
		families = append(families, FontFamily{Name: state.opt.FontFamily})
	}
	return Font{families: families, style: style, stretch: stretch, weight: weight, variations: variations}
}

func fontFamilyFromSt(f stFontFamily) FontFamily {
	switch f.Kind {
	case stFontFamilySerif:
		return FontFamily{Generic: text.GenericSerif}
	case stFontFamilySansSerif:
		return FontFamily{Generic: text.GenericSansSerif}
	case stFontFamilyCursive:
		return FontFamily{Generic: text.GenericCursive}
	case stFontFamilyFantasy:
		return FontFamily{Generic: text.GenericFantasy}
	case stFontFamilyMonospace:
		return FontFamily{Generic: text.GenericMonospace}
	}
	return FontFamily{Name: f.Name}
}

// parseFontVariationSettings parses `font-variation-settings`: normal | [ <string> <number> ]#, such as
// `"wght" 700, "wdth" 50`. Invalid items are skipped.
func parseFontVariationSettings(node svgNode) []FontVariation {
	n, ok := findAncestorWith(node, aidFontVariationSettings)
	if !ok {
		return nil
	}
	value, _ := n.attrStr(aidFontVariationSettings)
	if asciiEqualFold(value, "normal") || value == "" {
		return nil
	}
	var variations []FontVariation
	for _, part := range strings.Split(value, ",") {
		part = strings.TrimFunc(part, unicode.IsSpace)
		if part == "" {
			continue
		}
		part = strings.TrimLeftFunc(part, unicode.IsSpace)
		quote, size := utf8.DecodeRuneInString(part)
		if quote != '"' && quote != '\'' {
			continue
		}
		rest := part[size:]
		tag := rest
		if i := strings.IndexRune(rest, quote); i >= 0 {
			tag, rest = rest[:i], rest[i+1:]
		} else {
			rest = ""
		}
		// The tag must be exactly 4 bytes.
		if len(tag) != 4 {
			continue
		}
		v, ok := rustParseF32(strings.TrimFunc(strings.TrimLeftFunc(rest, unicode.IsSpace), unicode.IsSpace))
		if !ok {
			continue
		}
		var t [4]byte
		copy(t[:], tag)
		variations = append(variations, FontVariation{Tag: t, Value: v})
	}
	return variations
}

// asciiEqualFold is str::eq_ignore_ascii_case.
func asciiEqualFold(a, b string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := 0; i < len(a); i++ {
		x, y := a[i], b[i]
		if 'A' <= x && x <= 'Z' {
			x += 'a' - 'A'
		}
		if 'A' <= y && y <= 'Z' {
			y += 'a' - 'A'
		}
		if x != y {
			return false
		}
	}
	return true
}

// rustParseF32 is str::parse::<f32>: a decimal number (with optional sign, fraction and exponent),
// "inf", "infinity" or "nan" in any case. Out-of-range values become infinite.
func rustParseF32(s string) (float32, bool) {
	body := strings.TrimLeft(s, "+-")
	if len(s)-len(body) > 1 || body == "" {
		return 0, false
	}
	switch strings.ToLower(body) {
	case "inf", "infinity", "nan":
	default:
		digits := false
		for i := 0; i < len(body); i++ {
			c := body[i]
			switch {
			case c >= '0' && c <= '9':
				digits = true
			case c == '.' || c == 'e' || c == 'E' || c == '+' || c == '-':
			default:
				return 0, false
			}
		}
		if !digits {
			return 0, false
		}
	}
	v, err := strconv.ParseFloat(s, 32)
	if err != nil {
		if ne, ok := err.(*strconv.NumError); !ok || ne.Err != strconv.ErrRange {
			return 0, false
		}
	}
	return float32(v), true
}

// convFontStretch is conv_font_stretch; narrower and wider are not resolved properly.
func convFontStretch(node svgNode) FontStretch {
	n, ok := findAncestorWith(node, aidFontStretch)
	if !ok {
		return FontStretchNormal
	}
	v, _ := n.attrStr(aidFontStretch)
	switch v {
	case "narrower", "condensed":
		return FontStretchCondensed
	case "ultra-condensed":
		return FontStretchUltraCondensed
	case "extra-condensed":
		return FontStretchExtraCondensed
	case "semi-condensed":
		return FontStretchSemiCondensed
	case "semi-expanded":
		return FontStretchSemiExpanded
	case "wider", "expanded":
		return FontStretchExpanded
	case "extra-expanded":
		return FontStretchExtraExpanded
	case "ultra-expanded":
		return FontStretchUltraExpanded
	}
	return FontStretchNormal
}

// resolveFontWeight is resolve_font_weight. bolder and lighter step from 400 to 700 and 200, as Chrome
// does, not 500 and 300 as CSS 2 says.
func resolveFontWeight(node svgNode) uint16 {
	var nodes []svgNode
	for n := range node.Ancestors() {
		nodes = append(nodes, n)
	}
	weight := 400
	bound := func(v int) int { return max(100, min(900, v)) }
	// Reversed, skipping the root.
	for i := len(nodes) - 2; i >= 0; i-- {
		v, _ := nodes[i].attrStr(aidFontWeight)
		switch v {
		case "normal":
			weight = 400
		case "bold":
			weight = 700
		case "100", "200", "300", "400", "500", "600", "700", "800", "900":
			weight, _ = strconv.Atoi(v)
		case "bolder":
			step := 100
			if weight == 400 {
				step = 300
			}
			weight = bound(weight + step)
		case "lighter":
			step := 100
			if weight == 400 {
				step = 200
			}
			weight = bound(weight - step)
		}
	}
	return uint16(weight)
}

// resolvePositionsList resolves x, y, dx and dy per character (a Unicode code point). A tspan's lists
// apply to its own characters and its descendants', clamped to them: `a<tspan x="10 20 30">bc</tspan>d`
// gives [None, 10, 20, None], and an inner tspan's list overrides the outer one's.
func resolvePositionsList(textNode svgNode, state *converterState) []charPosition {
	list := make([]charPosition, countChars(textNode))
	offset := 0
	for child := range textNode.Descendants() {
		if child.IsElement() {
			// Text positions on `textPath` are ignored.
			if !child.hasTagName(eidText) && !child.hasTagName(eidTspan) {
				continue
			}
			childChars := countChars(child)
			push := func(a aid, field func(*charPosition) **float32) {
				nums, ok := convertList(child, a, state)
				if !ok {
					return
				}
				n := min(len(nums), childChars)
				for i := 0; i < n; i++ {
					v := nums[i]
					*field(&list[offset+i]) = &v
				}
			}
			push(aidX, func(p *charPosition) **float32 { return &p.x })
			push(aidY, func(p *charPosition) **float32 { return &p.y })
			push(aidDx, func(p *charPosition) **float32 { return &p.dx })
			push(aidDy, func(p *charPosition) **float32 { return &p.dy })
		} else if child.IsText() {
			offset += utf8.RuneCountInString(child.Text())
		}
	}
	return list
}

// resolveRotateList resolves the rotation per character as the SVG 1.1 spec explains: a character
// past an element's rotate list takes the last angle given.
func resolveRotateList(textNode svgNode) []float32 {
	list := make([]float32, countChars(textNode))
	var last float32
	offset := 0
	for child := range textNode.Descendants() {
		if child.IsElement() {
			if rotate, ok := child.attrNumberList(aidRotate); ok {
				for i := 0; i < countChars(child); i++ {
					if i < len(rotate) {
						list[offset+i] = rotate[i]
						last = rotate[i]
					} else {
						list[offset+i] = last
					}
				}
			}
		} else if child.IsText() {
			offset += utf8.RuneCountInString(child.Text())
		}
	}
	return list
}

// resolveDecoration is resolve_decoration. A decoration set on any ancestor (even outside the `text`)
// applies; its fill and stroke come from the closest ancestor that sets it, or the `text` element.
func resolveDecoration(tspan svgNode, state *converterState, cache *converterCache) TextDecoration {
	find := func(node svgNode, value string) bool {
		v, ok := node.attrStr(aidTextDecoration)
		if !ok {
			return false
		}
		for _, part := range strings.Split(v, " ") {
			if part == value {
				return true
			}
		}
		return false
	}
	gen := func(value string) *TextDecorationStyle {
		found := false
		for n := range tspan.Ancestors() {
			if find(n, value) {
				found = true
				break
			}
		}
		if !found {
			return nil
		}
		var node svgNode
		hasNode := false
		for n := range tspan.Ancestors() {
			if find(n, value) || n.hasTagName(eidText) {
				node, hasNode = n, true
				break
			}
		}
		s := &TextDecorationStyle{}
		if hasNode {
			s.fill = resolveFill(node, true, state, cache)
			s.stroke = resolveStroke(node, true, state, cache)
		}
		return s
	}
	var d TextDecoration
	d.underline = gen("underline")
	d.overline = gen("overline")
	d.lineThrough = gen("line-through")
	return d
}

// convertBaselineShift is convert_baseline_shift: the shifts of node and its ancestors up to (not
// including) the `text` element, node first; empty when all are `baseline`.
func convertBaselineShift(node svgNode, state *converterState) []BaselineShift {
	var shift []BaselineShift
	for n := range node.Ancestors() {
		if n.hasTagName(eidText) {
			break
		}
		if l, ok := svgTryAttr(n, aidBaselineShift, svgParseLength); ok {
			if l.Unit == stLengthUnitPercent {
				v := float32(resolveFontSize(n, state) * float32(float32(l.Number)/100))
				shift = append(shift, BaselineShift{Kind: BaselineShiftNumber, Number: v})
			} else {
				v := convertLength(l, n, aidBaselineShift, unitsObjectBoundingBox, state)
				shift = append(shift, BaselineShift{Kind: BaselineShiftNumber, Number: v})
			}
		} else if s, ok := n.attrStr(aidBaselineShift); ok {
			switch s {
			case "sub":
				shift = append(shift, BaselineShift{Kind: BaselineShiftSubscript})
			case "super":
				shift = append(shift, BaselineShift{Kind: BaselineShiftSuperscript})
			default:
				shift = append(shift, BaselineShift{Kind: BaselineShiftBaseline})
			}
		}
	}
	allBaseline := true
	for _, s := range shift {
		allBaseline = allBaseline && s.Kind == BaselineShiftBaseline
	}
	if allBaseline {
		return nil
	}
	return shift
}

func countChars(node svgNode) int {
	n := 0
	for d := range node.Descendants() {
		if d.IsText() {
			n += utf8.RuneCountInString(d.Text())
		}
	}
	return n
}

// convertWritingMode is convert_writing_mode. SVG 2 has two writing modes, horizontal left-to-right and
// vertical right-to-left; the SVG 1.1 values map onto them (lr, lr-tb, rl, rl-tb are horizontal, tb and
// tb-rl vertical), and vertical-lr behaves as vertical-rl.
func convertWritingMode(textNode svgNode) WritingMode {
	n, ok := findAncestorWith(textNode, aidWritingMode)
	if !ok {
		return WritingModeLeftToRight
	}
	v, ok := n.attrStr(aidWritingMode)
	if !ok {
		v = "lr-tb"
	}
	switch v {
	case "tb", "tb-rl", "vertical-rl", "vertical-lr":
		return WritingModeTopToBottom
	}
	return WritingModeLeftToRight
}

// pathLength is path_length: the arc length of path, each segment measured as a kurbo cubic.
func pathLength(path *skia.Path) float64 {
	pts := path.Points()
	prevMX, prevMY := pts[0].X, pts[0].Y
	prevX, prevY := prevMX, prevMY
	length := 0.0
	it := path.Segments()
	for {
		seg, ok := it.Next()
		if !ok {
			break
		}
		var curve kurboCubic
		switch seg.Verb {
		case skia.VerbMove:
			prevMX, prevMY = seg.Pts[0].X, seg.Pts[0].Y
			prevX, prevY = prevMX, prevMY
			continue
		case skia.VerbLine:
			curve = kurboCubicFromLine(prevX, prevY, seg.Pts[0].X, seg.Pts[0].Y)
		case skia.VerbQuad:
			curve = kurboQuad{
				kurboPoint{float64(prevX), float64(prevY)},
				kurboPoint{float64(seg.Pts[0].X), float64(seg.Pts[0].Y)},
				kurboPoint{float64(seg.Pts[1].X), float64(seg.Pts[1].Y)},
			}.raise()
		case skia.VerbCubic:
			curve = kurboCubic{
				kurboPoint{float64(prevX), float64(prevY)},
				kurboPoint{float64(seg.Pts[0].X), float64(seg.Pts[0].Y)},
				kurboPoint{float64(seg.Pts[1].X), float64(seg.Pts[1].Y)},
				kurboPoint{float64(seg.Pts[2].X), float64(seg.Pts[2].Y)},
			}
		case skia.VerbClose:
			curve = kurboCubicFromLine(prevX, prevY, prevMX, prevMY)
		}
		length += curve.arclen(0.5)
		prevX, prevY = float32(curve.P3.X), float32(curve.P3.Y)
	}
	return length
}
