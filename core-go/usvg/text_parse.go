func svgParseTextAnchor(_ svgNode, _ aid, v string) (TextAnchor, bool) {
	switch v {
	case "start":
		return TextAnchorStart, true
	case "middle":
		return TextAnchorMiddle, true
	case "end":
		return TextAnchorEnd, true
	}
	return 0, false
}

